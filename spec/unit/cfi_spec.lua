local CFI = require("src.zoterocfi")
local Range = require("src.zoterocfirange")
local XML = require("src.zoteroxml")

describe("EPUB point and range conversion", function()
    it("resolves encoded points against a mixed-content tree", function()
        local tree = XML.parse('<html><body><p id="passage">Hello <b>world</b>!</p></body></html>')
        local html = XML.find(tree, "html")
        local text = XML.children(XML.find(tree, "p"), "#text")[2]
        local cfi = CFI.encode(text, 1, "/6/2")
        local node, offset = CFI.resolve(html, CFI.parse(cfi))
        assert.equals(text, node)
        assert.equals(1, offset)
    end)
    it("accepts native unwrapped settings and escaped ID assertions", function()
        local point = CFI.parse("/6/4!/2[an^]id]/1:3")
        assert.equals(2, point.spine)
        assert.equals("an]id", point.steps[1].assertion)
        assert.equals(3, point.offset)
    end)
    it("rejects malformed and unsupported point locations", function()
        for _, point in ipairs({ "bad", "epubcfi(/6/3!/2/1:0)", "epubcfi(/6/2!/0)",
            "epubcfi(/6/2!/2[id)", "epubcfi(/6/2!/2/1:0~1)" }) do
            assert.has_error(function() CFI.parse(point) end)
        end
    end)
    it("round trips ranges with commas inside assertions", function()
        local first, last = "epubcfi(/6/2!/2[a^,b]/2/1:0)", "epubcfi(/6/2!/2[a^,b]/2/1:8)"
        local a, b = Range.split(Range.join(first, last))
        assert.equals(first, a)
        assert.equals(last, b)
    end)
    it("rejects ranges across spine entries", function()
        assert.has_error(function() Range.join("epubcfi(/6/2!/2/1:0)", "epubcfi(/6/4!/2/1:1)") end)
        assert.has_error(function() Range.split("epubcfi(/6/2!/2/1:0)") end)
    end)
end)

describe("XML boundary", function()
    it("preserves mixed text, decodes entities and normalizes line endings", function()
        local tree = XML.parse("<p>a&amp;b\r\n<b>bold</b>end</p>")
        local p = XML.find(tree, "p")
        assert.equals("a&b\n", XML.children(p, "#text")[1].text)
        assert.equals(1, #XML.children(p))
        assert.is_nil(XML.find(tree, "absent"))
    end)
    it("rejects entity declarations and mismatched tags", function()
        assert.has_error(function() XML.parse('<!ENTITY x "secret"><p>&x;</p>') end)
        assert.has_error(function() XML.parse("<p></b>") end)
        assert.has_error(function() XML.parse("<p>") end)
    end)
end)
