local ErrorText = require("src.zoteroerrortext")

describe("User-facing error text", function()
    it("drops the chunk and line LuaJIT adds to raised messages", function()
        -- busted replaces the global assert, so raise the way Lua's own assert does.
        local ok, err = pcall(function() error("CFI targets text omitted by the native reader") end)
        assert.is_false(ok)
        assert.truthy(err:find("%.lua:%d+: "))
        assert.equals("CFI targets text omitted by the native reader", ErrorText.strip(err))
    end)
    it("drops every location a rethrown message gained", function()
        local text = "plugins/zotero.koplugin/src/zoterohighlightcodec.lua:76: src/zoteroepub.lua:226: Not found"
        assert.equals("Not found", ErrorText.strip(text))
    end)
    it("keeps messages without a location and colons inside the reason", function()
        assert.equals("Zotero request timed out", ErrorText.strip("Zotero request timed out"))
        assert.equals("HTTP 412: version changed", ErrorText.strip("HTTP 412: version changed"))
        assert.equals("Could not read /a/b.lua:3: x", ErrorText.strip("Could not read /a/b.lua:3: x"))
    end)
    it("describes non-string error values", function()
        assert.equals("nil", ErrorText.strip(nil))
        assert.equals("42", ErrorText.strip(42))
    end)
end)
